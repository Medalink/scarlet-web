<?php

namespace App\Actions\Crests;

use InvalidArgumentException;

final class RenderCrestKit
{
    private const array REQUIRED = ['center', 'viewBox', 'attaches', 'scopes', 'quality', 'material', 'band', 'gem', 'ink', 'light', 'nearAt', 'unearned', 'glyphSize', 'pieces'];

    private const string TIER = 'array{name: string, color: string, deep: string|null, frame: string|null, field: float|int, plain: float|int, glyph: string, crown: string|null, banner: string|null, side: string|null, rays: string|null, gem: string|null, ghost: float|int, near: float|int, on: string}';

    /** @param  array<string, mixed>  $kit  the decoded resources/crests/kit.json */
    public function handle(array $kit): string
    {
        foreach (self::REQUIRED as $key) {
            if (! array_key_exists($key, $kit)) {
                throw new InvalidArgumentException('The crest kit has no `'.$key.'`.');
            }
        }

        $consts = [
            ['int', 'CX', $kit['center'][0], null],
            ['int', 'CY', $kit['center'][1], null],
            ['string', 'VIEW_FULL', $kit['viewBox']['full'], null],
            ['string', 'VIEW_COMPACT', $kit['viewBox']['compact'], null],
            ['array', 'ATTACHES', $kit['attaches'], 'list<string|null>'],
            ['array', 'SCOPES', $kit['scopes'], 'array<string, array{shield: string, side: string, ring?: string, glyphY: float|int}>'],
            ['array', 'QUALITY', $kit['quality'], 'array<int, '.self::TIER.'>'],
            ['array', 'MATERIAL', $kit['material'], 'array<string, array{top: string, bottom: string, flat: string}>'],
            ['array', 'BAND', $kit['band'], 'array{0: float|int, 1: float|int, 2: float|int, 3: float|int}'],
            ['array', 'GEM_AT', $kit['gem']['at'], 'array{0: float|int, 1: float|int}'],
            ['float', 'GEM_SETTING', $kit['gem']['setting'], null],
            ['string', 'INK', $kit['ink'], null],
            ['string', 'LIGHT', $kit['light'], null],
            ['float', 'NEAR_AT', $kit['nearAt'], null],
            ['float', 'UNEARNED_FILL', $kit['unearned']['fill'], null],
            ['float', 'UNEARNED_RIM', $kit['unearned']['rim'], null],
            ['float', 'UNEARNED_GLYPH', $kit['unearned']['glyph'], null],
            ['float', 'GLYPH', $kit['glyphSize'], null],
            ['array', 'PIECES', $kit['pieces'], 'array<string, array{d: string, box: array{0: float|int, 1: float|int, 2: float|int, 3: float|int}, fill: string, back?: bool}>'],
        ];

        $out = "<?php\n\nnamespace App\\View\\Sc;\n\n/** Generated by `artisan crests:kit` from resources/crests/kit.json. Change the kit, not this file. */\nfinal class CrestKit\n{\n";
        $blocks = [];
        foreach ($consts as [$type, $name, $value, $shape]) {
            $doc = $shape === null ? '' : "    /** @var $shape */\n";
            $blocks[] = $doc.'    public const '.$type.' '.$name.' = '.$this->literal($type === 'float' ? (float) $value : $value, 1).';';
        }

        return $out.implode("\n\n", $blocks)."\n}\n";
    }

    private function literal(mixed $value, int $depth): string
    {
        if (is_array($value)) {
            return $this->array($value, $depth);
        }

        return match (true) {
            $value === null => 'null',
            is_bool($value) => $value ? 'true' : 'false',
            is_int($value) => (string) $value,
            is_float($value) => var_export($value, true),
            is_string($value) => "'".addcslashes($value, "'\\")."'",
            default => throw new InvalidArgumentException('The crest kit holds a value that is not JSON.'),
        };
    }

    /** @param  array<array-key, mixed>  $items */
    private function array(array $items, int $depth): string
    {
        $list = array_is_list($items);
        $nested = $depth === 1 && $items !== [] && array_all($items, fn (mixed $item): bool => is_array($item));
        $parts = [];
        foreach ($items as $key => $item) {
            $parts[] = ($list ? '' : "'".addcslashes((string) $key, "'\\")."' => ").$this->literal($item, $depth + 1);
        }
        if (! $nested) {
            return '['.implode(', ', $parts).']';
        }
        $pad = str_repeat('    ', $depth + 1);

        return "[\n".$pad.implode(",\n".$pad, $parts).",\n".str_repeat('    ', $depth).']';
    }
}
