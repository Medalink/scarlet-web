<?php

namespace Scarlet\Analysis\Guidance;

use RuntimeException;
use Scarlet\Analysis\HouseRules;

final class RuleTable
{
    /** @return list<array{id:string,rule:string,fix:string,mode:string}> */
    public static function collect(): array
    {
        $rows = [];
        foreach (HouseRules::definitions() as $id => $rule) {
            $rows[] = ['id' => $id, 'rule' => $rule->rule, 'fix' => $rule->fix, 'mode' => $rule->mode->name];
        }
        usort($rows, fn (array $a, array $b): int => $a['id'] <=> $b['id']);

        return $rows;
    }

    /**
     * Deterministic render between the house-rules markers; sorted by id, no timestamps.
     *
     * @param  list<array{id:string,rule:string,fix:string,mode:string}>  $rows
     * @param  list<string>  $facts
     */
    public static function render(array $rows, array $facts): string
    {
        usort($rows, fn (array $a, array $b): int => $a['id'] <=> $b['id']);
        $lines = [
            '<!-- house-rules:start -->',
            '## Analyzer house rules',
            '',
            'Generated by `composer guidance` from `#[HouseRule]` attributes. `composer analyse` fails on a stale block (`guidance.stale`).',
            '',
            '| Identifier | Mode | Rule | Fix |',
            '| --- | --- | --- | --- |',
        ];
        foreach ($rows as $row) {
            $lines[] = '| `'.$row['id'].'` | '.$row['mode'].' | '.self::cell($row['rule']).' | '.self::cell($row['fix']).' |';
        }
        if ($facts !== []) {
            $lines[] = '';
            $lines[] = 'Facts the analysis knows:';
            $lines[] = '';
            foreach ($facts as $fact) {
                $lines[] = '- '.$fact;
            }
        }

        return implode("\n", $lines)."\n<!-- house-rules:end -->";
    }

    /** @return list<string> */
    public static function facts(string $root): array
    {
        return [
            'PHPStan runs Larastan at level '.self::phpstanLevel($root).' with no baseline file.',
        ];
    }

    public static function phpstanLevel(string $root): int
    {
        $neon = file_get_contents($root.'/phpstan.neon');
        if ($neon === false || preg_match('/^\s*level:\s*(\d+)/m', $neon, $matches) !== 1) {
            throw new RuntimeException('Cannot read the PHPStan level from phpstan.neon');
        }

        return (int) $matches[1];
    }

    public static function write(string $path, array $rows, array $facts): void
    {
        $content = file_get_contents($path);
        if ($content === false) {
            throw new RuntimeException('Cannot read '.$path);
        }
        $rendered = self::render($rows, $facts);
        $pattern = '/(<!-- house-rules:start -->.*?<!-- house-rules:end -->|<!-- house-rule-table:start -->.*?<!-- house-rule-table:end -->)/s';
        if (preg_match($pattern, $content) !== 1) {
            throw new RuntimeException('No house-rules block found in '.$path);
        }
        $updated = preg_replace_callback($pattern, fn (): string => $rendered, $content, limit: 1)
            ?? throw new RuntimeException('Cannot replace the house-rules block');
        if (file_put_contents($path, $updated) === false) {
            throw new RuntimeException('Cannot write '.$path);
        }
    }

    private static function cell(string $value): string
    {
        return str_replace('|', '\|', $value);
    }
}
