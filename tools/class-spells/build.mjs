#!/usr/bin/env node
// Writes part/src/sets.rs: the spell ids that the decoder's class tallies match, one sorted list per set of
// tools/class-spells/sets.mjs. It reads the client's own SpellName table (build 1.60.1.71037) as CSV, either from a
// CSV file or from a local file server for the client (`/dbc/export/csv?name=SpellName&build=1.60.1.71037`), and
// matches each set's names against it: every id that carries a name, all ranks. It prints the id count of each set
// and fails when a name matches no id, which means the client calls the spell something else.
// Usage: node tools/class-spells/build.mjs [csv file or server address] [out file]
import { readFileSync, writeFileSync } from 'node:fs';
import { SETS } from './sets.mjs';

const BUILD = '1.60.1.71037';
const DEFAULT_SERVER = 'http://127.0.0.1:5123';
const [source = DEFAULT_SERVER, out = 'part/src/sets.rs'] = process.argv.slice(2);

const load = async () => {
    if (!source.startsWith('http')) return readFileSync(source, 'utf8');
    const response = await fetch(`${source}/dbc/export/csv?name=SpellName&build=${BUILD}`);
    if (!response.ok) throw new Error(`SpellName: ${response.status}`);
    return response.text();
};

const parseCsv = (text) => {
    const rows = [];
    let row = [];
    let field = '';
    let quoted = false;
    for (let at = 0; at < text.length; at++) {
        const c = text[at];
        if (quoted) {
            if (c !== '"') field += c;
            else if (text[at + 1] === '"') {
                field += '"';
                at++;
            } else quoted = false;
        } else if (c === '"') quoted = true;
        else if (c === ',') {
            row.push(field);
            field = '';
        } else if (c === '\n' || c === '\r') {
            if (c === '\r' && text[at + 1] === '\n') at++;
            row.push(field);
            field = '';
            if (row.length > 1) rows.push(row);
            row = [];
        } else field += c;
    }
    if (field !== '' || row.length) {
        row.push(field);
        rows.push(row);
    }
    return rows;
};

const rows = parseCsv(await load());
const [header, ...body] = rows;
const idColumn = header.indexOf('ID');
const nameColumn = header.indexOf('Name_lang');
if (idColumn < 0 || nameColumn < 0) throw new Error('SpellName has no ID and Name_lang columns');
const spells = body.map((row) => [Number(row[idColumn]), row[nameColumn]]).filter(([id]) => Number.isInteger(id));
const idsOf = new Map();
for (const [id, name] of spells) {
    if (!idsOf.has(name)) idsOf.set(name, []);
    idsOf.get(name).push(id);
}

const idsFor = (entry) => {
    if (typeof entry === 'string') return idsOf.get(entry) ?? [];
    if (entry.prefix) return spells.filter(([, name]) => name.startsWith(entry.prefix)).map(([id]) => id);
    const found = new Set(idsOf.get(entry.client) ?? []);
    return entry.ids.filter((id) => found.has(id));
};

const label = (entry) => (typeof entry === 'string' ? entry : (entry.prefix ?? entry.name));
const sets = {};
const missing = [];
for (const [key, entries] of Object.entries(SETS)) {
    const ids = new Set();
    for (const entry of entries) {
        const found = idsFor(entry);
        if (found.length === 0) missing.push(`${key}: ${label(entry)}`);
        for (const id of found) ids.add(id);
    }
    sets[key] = [...ids].sort((a, b) => a - b);
}
for (const [key, ids] of Object.entries(sets)) console.log(`${key.padEnd(9)} ${ids.length} ids`);
if (missing.length > 0) {
    console.error(`no id carries: ${missing.join('; ')}`);
    process.exit(1);
}

const constant = (key) => key.toUpperCase();
const variant = (key) => key.replace(/(^|_)(\w)/g, (_, __, letter) => letter.toUpperCase());
const wrap = (ids) => {
    const lines = [];
    let line = '   ';
    for (const id of ids) {
        const next = ` ${id},`;
        if (line.length + next.length > 100) {
            lines.push(line);
            line = '   ';
        }
        line += next;
    }
    lines.push(line);
    return lines.join('\n');
};

const keys = Object.keys(sets);
const text = [
    `//! The spell ids the class tallies match by name (docs/ROWS.md, \`class_tallies\`). Generated by`,
    `//! tools/class-spells/build.mjs from the client's SpellName table, build ${BUILD}; edit tools/class-spells/sets.mjs`,
    `//! and run the tool again instead of this file.`,
    '',
    '#[derive(Clone, Copy, PartialEq, Eq)]',
    'pub enum Set {',
    ...keys.map((key) => `    ${variant(key)},`),
    '}',
    '',
    ...keys.flatMap((key) => [
        '#[rustfmt::skip]',
        `const ${constant(key)}: &[i64] = &[`,
        wrap(sets[key]),
        '];',
        '',
    ]),
    'impl Set {',
    '    fn ids(self) -> &\'static [i64] {',
    '        match self {',
    ...keys.map((key) => `            Set::${variant(key)} => ${constant(key)},`),
    '        }',
    '    }',
    '',
    '    pub fn has(self, id: i64) -> bool {',
    '        self.ids().binary_search(&id).is_ok()',
    '    }',
    '}',
    '',
].join('\n');
writeFileSync(out, text);
console.log(`wrote ${out}`);
